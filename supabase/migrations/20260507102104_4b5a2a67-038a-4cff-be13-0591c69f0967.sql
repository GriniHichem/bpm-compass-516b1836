-- Table catalogue des licences autorisées (gérée côté serveur)
CREATE TABLE IF NOT EXISTS public.licenses (
  code text PRIMARY KEY,
  ordinal int NOT NULL,
  duration_days int, -- null = illimité
  used boolean NOT NULL DEFAULT false,
  used_at timestamptz,
  used_by_install text,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.licenses ENABLE ROW LEVEL SECURITY;

-- Aucun accès direct (seules les edge functions service-role peuvent lire/écrire)
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='licenses' AND policyname='no_direct_access') THEN
    CREATE POLICY "no_direct_access" ON public.licenses FOR ALL USING (false) WITH CHECK (false);
  END IF;
END $$;

